export type UserRole = "admin" | "employer";

export interface UserProfile {
  uid: string;
  email: string;
  name: string;
  role: UserRole;
  businessName?: string;
  createdAt: string;
}

export interface Worker {
  id: string; // Worker document/page ID
  employerId: string; // Matches creator business/employer Account UID
  name: string;
  email?: string;
  position: string; // Job title
  bankName: string;
  bankCode: string;
  accountNumber: string;
  accountName: string; // Resolved verified bank name
  subaccountCode: string; // ACCT_xxx generated by Paystack Split Payment API
  createdAt: string;
  idNumber?: string;
  cellNumber?: string;
  employerName?: string;
}

export interface Tip {
  id: string; // Paystack TX reference
  workerId: string;
  workerName: string;
  employerId: string;
  amount: number; // Total paid in ZAR (cents will be handled automatically)
  feeAmount: number; // 2% platform fee
  workerAmount: number; // 98% payout
  status: "pending" | "success" | "failed";
  reference: string;
  customerEmail: string;
  customerName?: string;
  createdAt: string;
}

// Global interface representing the Bank metadata supported by Paystack
export interface PaystackBank {
  name: string;
  code: string;
}
